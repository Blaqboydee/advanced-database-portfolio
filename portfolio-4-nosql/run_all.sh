#!/usr/bin/env bash
# Rebuilds the whole Portfolio 4 pipeline and regenerates evidence/ (~2 minutes):
#   PostgreSQL (system of record) -> exports -> MongoDB, Redis, Neo4j -> queries -> comparisons
# Requires Docker Desktop. Starts the NoSQL containers if they are not running.
#
# NOTE: this loads the large Portfolio 2 dataset into PostgreSQL. Run
# ../portfolio-1-database-design/run_all.sh afterwards to go back to the small one.
set -euo pipefail
cd "$(dirname "$0")"
ROOT=$(cd .. && pwd)

P1=/portfolio/portfolio-1-database-design/sql
P2=/portfolio/portfolio-2-query-optimisation/sql
P4=/portfolio/portfolio-4-nosql
psql_run()   { docker exec owotrust-pg sh -c "psql -X -U owotrust -d owotrust_bank $* 2>&1"; }
psql_out()   { docker exec owotrust-pg psql -X -q -At -U owotrust -d owotrust_bank -v ON_ERROR_STOP=1 "$@"; }
mongosh_run(){ docker exec owotrust-mongo mongosh --quiet "$@" 2>&1; }
cypher_run() { docker exec owotrust-neo4j cypher-shell -u neo4j -p owotrust_dev "$@" 2>&1; }
stamp()      { echo "-- run at $(date '+%Y-%m-%d %H:%M:%S %Z')"; }
step()       { echo "==> $*"; }
mkdir -p data evidence

step "0/7 Start containers and wait until healthy"
(cd "$ROOT" && docker compose --profile nosql up -d >/dev/null 2>&1)
for c in owotrust-pg owotrust-mongo owotrust-redis owotrust-neo4j; do
    until [ "$(docker inspect -f '{{.State.Health.Status}}' $c)" = healthy ]; do sleep 2; done
done
# MongoDB transactions need a replica set: initiate it once (no-op if it already exists)
mongosh_run --eval 'try { rs.status().ok } catch (e) { rs.initiate({_id: "rs0", members: [{_id: 0, host: "localhost:27017"}]}).ok }' >/dev/null
until [ "$(mongosh_run --eval 'db.hello().isWritablePrimary')" = true ]; do sleep 1; done

step "1/7 PostgreSQL: Portfolio 1 schema + Portfolio 2 bulk data + devices and fraud ring"
{
  stamp
  psql_run -q -v ON_ERROR_STOP=1 -f $P1/01_schema.sql | grep -v NOTICE || true
  psql_run -q -v ON_ERROR_STOP=1 -f $P1/02_seed_data.sql
  psql_run -q -v ON_ERROR_STOP=1 -f $P2/01_bulk_data.sql | tail -25
  psql_run -v ON_ERROR_STOP=1 -f $P4/source/01_prepare_source_data.sql
} > evidence/01_source_data_output.txt

step "2/7 Export: documents (NDJSON) and graph (CSV) from PostgreSQL"
psql_out -f $P4/source/02_export_customers.sql > data/customers.ndjson
psql_out -v FETCH_COUNT=5000 -f $P4/source/03_export_statements.sql > data/statements.ndjson
for g in customers accounts devices transfers cashouts; do
    docker exec owotrust-pg psql -X -q -U owotrust -d owotrust_bank -v ON_ERROR_STOP=1 \
        -f $P4/source/graph/$g.sql > data/graph_$g.csv
done
{
  stamp
  echo "Exported files (regenerated by run_all.sh, not committed to Git):"
  for f in data/*; do printf '  %-28s %9s lines  %6s\n' "$(basename "$f")" "$(wc -l < "$f" | tr -d ' ')" "$(du -h "$f" | cut -f1)"; done
} > evidence/02_export_summary.txt
# pretty-printed samples of each document type, for the README and the assessor
python3 -c "import json,sys; print(json.dumps(json.loads(open('data/customers.ndjson').readlines()[0]), indent=2))" \
    > evidence/sample_customer_document.json
grep -m1 '"3900000001:2026-10"' data/statements.ndjson \
    | python3 -c "import json,sys; print(json.dumps(json.load(sys.stdin), indent=2))" > evidence/sample_statement_document.json

step "3/7 MongoDB: validated collections, import, queries, transactions"
{
  stamp
  mongosh_run $P4/mongodb/01_setup.js
  docker exec owotrust-mongo mongoimport --db owotrust --collection customers \
      --file $P4/data/customers.ndjson --numInsertionWorkers 4 2>&1 | tail -1
  docker exec owotrust-mongo mongoimport --db owotrust --collection account_statements \
      --file $P4/data/statements.ndjson --numInsertionWorkers 4 2>&1 | tail -1
} > evidence/03_mongodb_setup_import.txt
{ stamp; mongosh_run $P4/mongodb/02_queries.js; } > evidence/04_mongodb_queries.txt
{ stamp; mongosh_run $P4/mongodb/03_transaction.js; } > evidence/05_mongodb_transaction.txt

step "4/7 Redis: sessions, OTP, rate limiting, idempotency, leaderboard, cache, benchmark"
./redis/redis_demo.sh > evidence/06_redis_demo.txt 2>&1

step "5/7 Neo4j: load the graph and run the fraud queries"
{ stamp; cypher_run --format plain -f $P4/neo4j/01_load.cypher; } > evidence/07_neo4j_load.txt
{ stamp; cypher_run --format verbose -f $P4/neo4j/02_fraud_queries.cypher; } > evidence/08_neo4j_fraud_queries.txt

step "6/7 PostgreSQL comparison queries"
{ stamp; psql_run -f $P4/source/04_postgres_comparison.sql; } > evidence/09_postgres_comparison.txt

step "7/7 Automatic cross-checks"
python3 - <<'PY' | tee evidence/10_cross_checks.txt
import re
mongo = open("evidence/04_mongodb_queries.txt").read()
pg    = open("evidence/09_postgres_comparison.txt").read()
m5 = mongo.split("M5.")[1].split("M6.")[0]
mongo_rows = {c: (int(n), t) for c, n, t in re.findall(r"_id: '(\w+)',\s+debits: (\d+),\s+total: Decimal128\('([\d.]+)'\)", m5)}
x1 = pg.split("X1.")[1].split("X2.")[0]
pg_rows = {c: (int(n), t) for c, n, t in re.findall(r"^\s*(\w+)\s+\|\s+(\d+)\s+\|\s+([\d.]+)\s*$", x1, re.M)}
print("MongoDB M5 vs PostgreSQL X1 (October debits by channel):",
      "MATCH" if mongo_rows and mongo_rows == pg_rows else "MISMATCH", f"({len(mongo_rows)} channels)")
print("MongoDB M4 statement closing balance (P2 Q2 gave 5100.00):",
      re.search(r"closingBalance: Decimal128\('([\d.]+)'\)", mongo.split("M4.")[1]).group(1))
neo = open("evidence/08_neo4j_fraud_queries.txt").read()
print("Neo4j G2 cycles found:", neo.count('["3900000001", "3900000002", "3900000003", "3900000004", "3900000001"]'),
      "| PostgreSQL X3 cycles found:", pg.count("{3900000001,3900000002,3900000003,3900000004,3900000001}"))
PY
echo "Done. Evidence written to $(pwd)/evidence/"
